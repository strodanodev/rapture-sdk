/**
 * The two vendored sets, copied byte for byte (line endings normalised to LF) and pinned by sha256 in a manifest each:
 *
 *   vendor/litnode/   LitNode's title bundler and conformance suite, with the sandbox it runs titles in and the
 *                     protocol modules they need (Apache-2.0, https://github.com/strodanodev/litnode). With these the
 *                     sample ruleset is built and checked by exactly the code every node runs, with no LitNode
 *                     checkout and no network. log.js and keys.js are there for the relay test (chain head, ledger
 *                     and relay signatures, as a node checks them).
 *   src/vendor/tcg/   the Rapture SDK TCG kit's wallet and holdings layer (web/lib) and its arcade-shell client
 *                     (src/client/shell.ts), so the board client seats wallets and arcade players exactly as the TCG
 *                     client does, and a scaffolded board game needs nothing but this folder.
 *
 *   node scripts/vendor.mjs                    copy both sets: LitNode from LITNODE_DIR (or --litnode <dir>), the TCG
 *                                              kit from ../tcg (or --tcg <dir>); a set whose source is missing is kept
 *   node scripts/vendor.mjs --check            exit 1 when a copy differs from its manifest (offline: CI and `check`)
 *   node scripts/vendor.mjs --check --source   also compare with the sources, where they are on disk
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const argv = process.argv.slice(2);
const opt = (name) => (argv.includes(`--${name}`) ? argv[argv.indexOf(`--${name}`) + 1] : undefined);

export const SETS = [
  {
    name: 'litnode',
    out: join(root, 'vendor', 'litnode'),
    source: () => opt('litnode') ?? process.env.LITNODE_DIR,
    version: (src) => `litnode ${JSON.parse(readFileSync(join(src, 'package.json'), 'utf8')).version}`,
    license: 'Apache-2.0 (LitNode, https://github.com/strodanodev/litnode)',
    // [copy, source]: same paths, so the modules' own relative imports keep working
    files: ['tools/bundle-title.mjs', 'sdk/conformance.mjs', 'sdk/bundle.mjs', 'node/sandbox.js', 'node/sandbox-child.mjs', 'protocol/canonical.js', 'protocol/stats.js', 'protocol/log.js', 'protocol/keys.js'].map((f) => [f, f]),
  },
  {
    name: 'tcg',
    out: join(root, 'src', 'vendor', 'tcg'),
    source: () => opt('tcg') ?? join(root, '..', 'tcg'),
    version: (src) => `@rapture-sdk/tcg ${JSON.parse(readFileSync(join(src, 'package.json'), 'utf8')).version}`,
    license: 'Apache-2.0 (the Rapture SDK TCG kit, packages/tcg)',
    files: [...['wallet.js', 'holdings.js', 'chain.js', 'abi.js', 'tiers.js'].map((f) => [f, `web/lib/${f}`]), ['shell.ts', 'src/client/shell.ts']],
  },
];

const lf = (b) => b.toString('utf8').replace(/\r\n/g, '\n');
const sha = (text) => createHash('sha256').update(text).digest('hex');
const manifestOf = (set) => join(set.out, 'MANIFEST.json');

/** The copies that differ from their manifest (empty: all good). */
export function drift(set) {
  if (!existsSync(manifestOf(set))) return ['MANIFEST.json'];
  const m = JSON.parse(readFileSync(manifestOf(set), 'utf8'));
  return set.files.filter(([f]) => !existsSync(join(set.out, f)) || m.files[f] !== sha(lf(readFileSync(join(set.out, f))))).map(([f]) => f);
}

/** The copies that differ from the source on disk, or null when the source is not here. */
export function sourceDrift(set) {
  const src = set.source();
  if (!src || !existsSync(join(src, set.files[0][1]))) return null;
  return set.files.filter(([f, s]) => !existsSync(join(set.out, f)) || lf(readFileSync(join(src, s))) !== lf(readFileSync(join(set.out, f)))).map(([f]) => f);
}

function copy(set) {
  const src = set.source();
  if (!src || !existsSync(join(src, set.files[0][1]))) { console.log(`${set.name}: no source (${src ?? 'set LITNODE_DIR or --litnode <dir>'}), kept`); return; }
  const files = {};
  for (const [f, s] of set.files) {
    const text = lf(readFileSync(join(src, s)));
    mkdirSync(dirname(join(set.out, f)), { recursive: true });
    writeFileSync(join(set.out, f), text);
    files[f] = sha(text);
  }
  const manifest = { note: 'generated by scripts/vendor.mjs: do not edit the copies, re-vendor instead', from: set.version(src), license: set.license, files };
  writeFileSync(manifestOf(set), `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(`${set.name}: copied ${set.files.length} files from ${manifest.from}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (argv.includes('--check')) {
    let bad = false;
    for (const set of SETS) {
      const d = drift(set);
      if (d.length) { bad = true; console.error(`${set.name}: edited or missing: ${d.join(', ')} (run node scripts/vendor.mjs)`); continue; }
      const m = JSON.parse(readFileSync(manifestOf(set), 'utf8'));
      const s = argv.includes('--source') ? sourceDrift(set) : null;
      if (s?.length) { bad = true; console.error(`${set.name}: differs from ${set.source()}: ${s.join(', ')} (run node scripts/vendor.mjs)`); continue; }
      console.log(`${set.name}: ${set.files.length} files match ${m.from}${s ? ' and the source on disk' : ''}`);
    }
    process.exit(bad ? 1 : 0);
  }
  for (const set of SETS) copy(set);
}
